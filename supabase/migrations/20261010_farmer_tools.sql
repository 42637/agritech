-- Private server-written records for crop-photo assessments and direct produce sales.
CREATE TABLE IF NOT EXISTS public.crop_disease_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farm_id BIGINT,
    crop_name VARCHAR(100) NOT NULL,
    symptoms TEXT NOT NULL DEFAULT '',
    language VARCHAR(10) NOT NULL DEFAULT 'en',
    image_path TEXT NOT NULL,
    assessment_json JSONB NOT NULL,
    ai_model VARCHAR(80) NOT NULL DEFAULT 'Gemini Vision',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_crop_disease_reports_farm_created
    ON public.crop_disease_reports (farm_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.produce_listings (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    farm_id BIGINT,
    seller_name VARCHAR(100) NOT NULL,
    seller_phone VARCHAR(20) NOT NULL,
    crop_name VARCHAR(100) NOT NULL,
    quantity_kg NUMERIC(12, 2) NOT NULL CHECK (quantity_kg > 0),
    price_per_kg NUMERIC(12, 2) NOT NULL CHECK (price_per_kg > 0),
    location VARCHAR(180) NOT NULL,
    harvest_date DATE,
    quality_grade VARCHAR(80) NOT NULL DEFAULT 'Not graded',
    details TEXT NOT NULL DEFAULT '',
    status VARCHAR(20) NOT NULL DEFAULT 'available' CHECK (status IN ('available', 'sold')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_produce_listings_available_created
    ON public.produce_listings (status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.produce_purchase_requests (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    listing_id UUID NOT NULL REFERENCES public.produce_listings(id),
    buyer_name VARCHAR(100) NOT NULL,
    buyer_phone VARCHAR(20) NOT NULL,
    seller_name VARCHAR(100) NOT NULL,
    seller_phone VARCHAR(20) NOT NULL,
    crop_name VARCHAR(100) NOT NULL,
    quantity_kg NUMERIC(12, 2) NOT NULL CHECK (quantity_kg > 0),
    price_per_kg NUMERIC(12, 2) NOT NULL CHECK (price_per_kg > 0),
    total_amount NUMERIC(14, 2) NOT NULL CHECK (total_amount > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'requested' CHECK (status IN ('requested', 'accepted', 'completed', 'cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_produce_purchase_requests_listing_created
    ON public.produce_purchase_requests (listing_id, created_at DESC);

