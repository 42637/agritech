-- A single atomic function reserves stock and records the direct buyer request.
CREATE OR REPLACE FUNCTION public.request_produce_purchase(
    p_listing_id UUID,
    p_buyer_name TEXT,
    p_buyer_phone TEXT,
    p_quantity_kg NUMERIC
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    listing public.produce_listings%ROWTYPE;
    request_id UUID;
    remaining NUMERIC(12, 2);
BEGIN
    IF p_quantity_kg IS NULL OR p_quantity_kg <= 0 THEN
        RAISE EXCEPTION 'Purchase quantity must be positive';
    END IF;

    SELECT * INTO listing
    FROM public.produce_listings
    WHERE id = p_listing_id AND status = 'available'
    FOR UPDATE;

    IF NOT FOUND OR p_quantity_kg > listing.quantity_kg THEN
        RAISE EXCEPTION 'Listing unavailable or requested quantity exceeds stock';
    END IF;

    INSERT INTO public.produce_purchase_requests (
        listing_id, buyer_name, buyer_phone, seller_name, seller_phone,
        crop_name, quantity_kg, price_per_kg, total_amount
    ) VALUES (
        listing.id, trim(p_buyer_name), trim(p_buyer_phone), listing.seller_name, listing.seller_phone,
        listing.crop_name, p_quantity_kg, listing.price_per_kg, p_quantity_kg * listing.price_per_kg
    ) RETURNING id INTO request_id;

    remaining := listing.quantity_kg - p_quantity_kg;
    UPDATE public.produce_listings
    SET quantity_kg = remaining,
        status = CASE WHEN remaining = 0 THEN 'sold' ELSE 'available' END,
        updated_at = CURRENT_TIMESTAMP
    WHERE id = listing.id;

    RETURN jsonb_build_object(
        'request_id', request_id,
        'listing_id', listing.id,
        'crop_name', listing.crop_name,
        'quantity_kg', p_quantity_kg,
        'price_per_kg', listing.price_per_kg,
        'total_amount', p_quantity_kg * listing.price_per_kg,
        'seller_name', listing.seller_name,
        'seller_phone', listing.seller_phone,
        'buyer_name', trim(p_buyer_name),
        'buyer_phone', trim(p_buyer_phone),
        'remaining_quantity_kg', remaining,
        'status', 'requested'
    );
END;
$$;

REVOKE ALL ON FUNCTION public.request_produce_purchase(UUID, TEXT, TEXT, NUMERIC) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.request_produce_purchase(UUID, TEXT, TEXT, NUMERIC) TO service_role;
